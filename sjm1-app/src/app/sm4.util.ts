function rotl(x: number, n: number): number {
  return ((x << n) | (x >>> (32 - n))) >>> 0;
}

function tau(a: number): number {
  return (
    ((SBOX[(a >>> 24) & 0xff] << 24) |
      (SBOX[(a >>> 16) & 0xff] << 16) |
      (SBOX[(a >>> 8) & 0xff] << 8) |
      SBOX[a & 0xff]) >>>
    0
  );
}

/** 数据轮线性变换 L */
function lData(b: number): number {
  return (b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)) >>> 0;
}

/** 密钥轮线性变换 L' */
function lKey(b: number): number {
  return (b ^ rotl(b, 13) ^ rotl(b, 23)) >>> 0;
}

function be32(bytes: Uint8Array, off: number): number {
  return ((bytes[off] << 24) | (bytes[off + 1] << 16) | (bytes[off + 2] << 8) | bytes[off + 3]) >>> 0;
}

/** 展开 128bit 密钥为 32 轮子密钥 */
function expandKey(key: Uint8Array): number[] {
  const w = [be32(key, 0) ^ FK[0], be32(key, 4) ^ FK[1], be32(key, 8) ^ FK[2], be32(key, 12) ^ FK[3]];
  for (let i = 0; i < 32; i++) {
    w.push((w[i] ^ lKey(tau(w[i + 1] ^ w[i + 2] ^ w[i + 3] ^ CK[i]))) >>> 0);
  }
  return w.slice(4);
}

/** 加密单个 16 字节分组 */
function encryptBlock(block: Uint8Array, rk: number[], out: Uint8Array, outOff: number): void {
  let x = [be32(block, 0), be32(block, 4), be32(block, 8), be32(block, 12)];
  for (let i = 0; i < 32; i++) {
    x = [x[1], x[2], x[3], (x[0] ^ lData(tau(x[1] ^ x[2] ^ x[3] ^ rk[i]))) >>> 0];
  }
  // 密文为逆序输出：X3 X2 X1 X0
  const words = [x[3], x[2], x[1], x[0]];
  for (let i = 0; i < 4; i++) {
    const w = words[i];
    out[outOff + i * 4] = (w >>> 24) & 0xff;
    out[outOff + i * 4 + 1] = (w >>> 16) & 0xff;
    out[outOff + i * 4 + 2] = (w >>> 8) & 0xff;
    out[outOff + i * 4 + 3] = w & 0xff;
  }
}

function parseHex(text: string): Uint8Array {
  const clean = text.trim().replace(/\s+/g, '');
  const out = new Uint8Array(clean.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(clean.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

function toHex(bytes: Uint8Array): string {
  let s = '';
  for (let i = 0; i < bytes.length; i++) {
    s += bytes[i].toString(16).padStart(2, '0').toUpperCase();
  }
  return s;
}

/**
 * SM4 ECB 模式加密（PKCS7 填充）。
 * @param plainText 明文，按 UTF-8 编码
 * @param keyHex 128bit 密钥的 Hex 字符串（32 个字符）
 * @returns 密文的大写 Hex 字符串
 */
export function sm4EcbEncryptHex(plainText: string, keyHex: string): string {
  const key = parseHex(keyHex);
  if (key.length !== 16) {
    throw new Error('SM4 密钥必须为 16 字节');
  }
  const rk = expandKey(key);
  const data = new TextEncoder().encode(plainText);
  const padLen = 16 - (data.length % 16);
  const padded = new Uint8Array(data.length + padLen);
  padded.set(data);
  padded.fill(padLen, data.length);
  const out = new Uint8Array(padded.length);
  for (let off = 0; off < padded.length; off += 16) {
    encryptBlock(padded.subarray(off, off + 16), rk, out, off);
  }
  return toHex(out);
}
